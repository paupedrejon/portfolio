export function filterPopularCities(query: string, limit = 8): string[] {
  const q = query.trim().toLowerCase().normalize("NFD").replace(/\p{M}/gu, "");
  if (!q) return [...POPULAR_CITIES].slice(0, limit);
  return POPULAR_CITIES.filter((c) =>
    c
      .toLowerCase()
      .normalize("NFD")
      .replace(/\p{M}/gu, "")
      .includes(q),
  ).slice(0, limit);
}
